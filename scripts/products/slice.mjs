#!/usr/bin/env node
/**
 * Product art -> assets/products/<id>.png and src/ui/productImages.ts.
 *
 *   node scripts/products/slice.mjs <sheet1.png> <sheet2.png> <sheet3.png> <sheet4.png> [earbuds.png]
 *
 * The sheets are 4 × 3 grids on a flat #EDEDED background (prompts in
 * scripts/products/PROMPTS.md), in PRODUCTS order. Each cell is cropped, its
 * background flood-filled to transparent from the edges (so light colors
 * inside a product survive), trimmed, centered on a transparent square and
 * saved at SIZE px. Needs ImageMagick 7 (`magick`).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, 'assets/products');
const SIZE = 192;
const COLS = 4;
const ROWS = 3;

// PRODUCTS order (src/config/products.ts), 12 per sheet.
const IDS = [
  'kettle-crisp', 'volt-bar', 'ridge-pretzels', 'oat-ember', 'lumen-gummies', 'saltline-peanuts',
  'cocoa-drift', 'crunchwell', 'ironleaf-jerky', 'northfield-cola', 'clearpeak-water', 'sparkline-lemon',
  'volt-energy', 'orchard-juice', 'harbor-tea', 'brew-seven', 'lift-protein', 'hot-coffee',
  'latte', 'hot-cocoa', 'green-tea-hot', 'capsule-critters', 'capsule-minis', 'card-transit',
  'blind-box', 'usb-c-cable', 'wall-charger', 'power-bank', 'earbuds', 'pain-relief',
  'bandages', 'allergy-tabs', 'sanitizer', 'masks', 'toothbrush-kit', 'cup-noodles',
  'ramen-spicy', 'pizza-slice', 'salad-bowl', 'sandwich', 'fruit-cup', 'bouquet',
  'umbrella', 'ice-bag', 'lager', 'house-red', 'soju', 'sake-cup',
]; // prettier-ignore

const [s1, s2, s3, s4, earbuds] = process.argv.slice(2);
if (!s4) {
  console.error('usage: slice.mjs sheet1 sheet2 sheet3 sheet4 [earbuds]');
  process.exit(1);
}

function cutout(src, crop, out) {
  const args = [src];
  if (crop) args.push('-crop', crop, '+repage');
  args.push(
    '-alpha', 'set', '-bordercolor', '#EDEDED', '-border', '2', '-fuzz', '7%', '-fill', 'none',
    '-draw', 'color 0,0 floodfill', '-shave', '2x2', '-trim', '+repage',
    '-resize', `${SIZE - 16}x${SIZE - 16}`, '-background', 'none', '-gravity', 'center',
    '-extent', `${SIZE}x${SIZE}`, '-strip', `PNG32:${out}`,
  ); // prettier-ignore
  execFileSync('magick', args);
}

[s1, s2, s3, s4].forEach((sheet, si) => {
  const [w, h] = execFileSync('magick', ['identify', '-format', '%w %h', sheet])
    .toString()
    .split(' ')
    .map(Number);
  const cw = Math.floor(w / COLS);
  const ch = Math.floor(h / ROWS);
  for (let r = 0; r < ROWS; r++)
    for (let c = 0; c < COLS; c++) {
      const id = IDS[si * 12 + r * COLS + c];
      cutout(sheet, `${cw}x${ch}+${c * cw}+${r * ch}`, path.join(OUT, `${id}.png`));
    }
});
// A generic replacement for the first earbuds drawing (it looked like a real product).
if (earbuds) cutout(earbuds, null, path.join(OUT, 'earbuds.png'));

writeFileSync(
  path.join(ROOT, 'src/ui/productImages.ts'),
  `// GENERATED by scripts/products/slice.mjs. Do not edit by hand.
// Product art (flat-shaded game icons, transparent PNG, ${SIZE} px), keyed by product id.

export const PRODUCT_IMAGES: Record<string, number> = {
${IDS.map((id) => `  '${id}': require('../../assets/products/${id}.png'),`).join('\n')}
};
`,
);
console.log(`${IDS.length} product images -> assets/products`);
