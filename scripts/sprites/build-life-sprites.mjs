#!/usr/bin/env node
/**
 * `npm run life-sprites` — pre-rendered street-life sprites for the map:
 * low-poly cars (sedan, hatchback, van, taxi × muted paints) and pedestrians
 * (4 outfits × 3 walk frames), 8 viewer-relative headings × 2 pitches ×
 * day/night, rendered in headless Chromium with the machine sprites' harness.
 *
 *   procedural three.js models (scripts/sprites/life/models.ts)
 *   -> orthographic renders, cropped symmetric around the ground center
 *   -> assets/sprites/life/{name}.png   (bundled via require())
 *   -> src/map/lifeSprites.ts           (generated)
 *
 * Scale: LIFE_PX_PER_METER at pixelRatio 2, i.e. half the machine sprites'
 * density. The map sizes both at true scale from their pts/m, so they match;
 * the lower density keeps ~600 small sprites at a few MB of PNG and memory.
 *
 * Options: --only=car|ped (render a subset; skips the generated module)
 */
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

import prettier from 'prettier';

import { b64ToBuf, bundle, launchWithBundle, ROOT } from './lib/harness.mjs';
import { encodePNG } from './lib/png.mjs';

const LIFE_PX_PER_METER = 24;
const PIXEL_RATIO = 2;
const SUPERSAMPLE = 4;

const OUT_DIR = path.join(ROOT, 'assets/sprites/life');
const GENERATED = path.join(ROOT, 'src/map/lifeSprites.ts');

const only = process.argv.find((a) => a.startsWith('--only='))?.slice(7);

async function main() {
  const t0 = Date.now();
  await mkdir(OUT_DIR, { recursive: true });
  const code = await bundle('scripts/sprites/life/render-entry.ts', 'LifeSprites');
  const { browser, page } = await launchWithBundle(code);
  const jobs = await page.evaluate(() => window.LifeSprites.jobs());

  if (!only)
    for (const f of await readdir(OUT_DIR)) if (f.endsWith('.png')) await rm(path.join(OUT_DIR, f));

  const names = [];
  const stats = [];
  let maxW = 0;
  let maxH = 0;
  let decoded = 0;
  for (let i = 0; i < jobs.length; i++) {
    const job = jobs[i];
    if (only && job.kind !== only) continue;
    const res = await page.evaluate(
      ([idx, cfg]) => window.LifeSprites.renderJob(idx, cfg),
      [i, { pxPerMeter: LIFE_PX_PER_METER, supersample: SUPERSAMPLE }],
    );
    let bytes = 0;
    for (const s of res.sprites) {
      const png = encodePNG({ width: s.width, height: s.height, data: b64ToBuf(s.rgba) });
      bytes += png.length;
      await writeFile(path.join(OUT_DIR, `${s.name}.png`), png);
      names.push(s.name);
      maxW = Math.max(maxW, s.width);
      maxH = Math.max(maxH, s.height);
      decoded += s.width * s.height * 4;
    }
    stats.push({
      model: `${job.kind}-${job.model}${job.kind === 'ped' ? `-f${job.frame}` : ''}`,
      sprites: res.sprites.length,
      triangles: res.triangles,
      KB: +(bytes / 1024).toFixed(1),
    });
  }
  await browser.close();
  if (!only) await writeModule(names);
  console.table(stats);
  const total = stats.reduce((s, x) => s + x.KB, 0);
  console.log(
    `${names.length} sprites, ${(total / 1024).toFixed(2)} MB of PNGs, ` +
      `largest ${maxW}×${maxH}px, ${(decoded / 1024 / 1024).toFixed(1)} MB decoded, ` +
      `${((Date.now() - t0) / 1000).toFixed(1)} s`,
  );
}

async function writeModule(names) {
  const lines = [
    '// GENERATED by scripts/sprites/build-life-sprites.mjs (`npm run life-sprites`). Do not edit by hand.',
    '//',
    '// Street-life sprites (cars, pedestrians) for the map. Orthographic renders of',
    '// procedural low-poly models, transparent background, soft contact shadow,',
    '// each cropped symmetric around the ground center: use `icon-anchor: center`.',
    '',
    "export { carSpriteName, personSpriteName } from './life/sprites';",
    '',
    '/** Map points per meter at icon-size 1 (pixels per meter ÷ pixelRatio). */',
    `export const LIFE_SPRITE_PTS_PER_METER = ${LIFE_PX_PER_METER / PIXEL_RATIO};`,
    '',
    '/** Image pixel ratio of every life sprite. */',
    `export const LIFE_SPRITE_PIXEL_RATIO = ${PIXEL_RATIO};`,
    '',
    `/** ${names.length} images: car-{model}-h{0..7}-p{30|60}-{day|night}, ped-{model}-f{frame}-h…-p…-{light}. */`,
    'export const LIFE_SPRITE_IMAGES: Record<string, number> = {',
    ...names.map((n) => `  '${n}': require('../../assets/sprites/life/${n}.png'),`),
    '};',
    '',
  ];
  const options = (await prettier.resolveConfig(GENERATED)) ?? {};
  await writeFile(
    GENERATED,
    await prettier.format(lines.join('\n'), { ...options, filepath: GENERATED }),
  );
  console.log(`  wrote ${path.relative(ROOT, GENERATED)} (${names.length} images)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
