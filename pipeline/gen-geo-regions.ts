/**
 * Writes src/data/geoRegions.ts: every country's UN sub-region and continent
 * (Natural Earth admin-0, public domain), for the expansion ladder.
 *
 *   npx tsx gen-geo-regions.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { countryAt } from './lib/countries';

const HERE = dirname(fileURLToPath(import.meta.url));
countryAt(0, 0); // downloads the file if needed
const geo = JSON.parse(
  readFileSync(join(HERE, 'out', 'naturalearth', 'ne_50m_admin_0_countries.geojson'), 'utf8'),
) as { features: { properties: Record<string, string> }[] };
const rows: Record<string, [string, string]> = {};
for (const f of geo.features) {
  const p = f.properties;
  const raw = p.ISO_A2_EH !== '-99' ? p.ISO_A2_EH : p.ISO_A2;
  if (!raw || raw === '-99') continue;
  // Natural Earth files the Caribbean and Central America under North America, as players expect.
  const continent = p.CONTINENT === 'Seven seas (open ocean)' ? 'Oceania' : p.CONTINENT;
  rows[raw.toUpperCase()] = [p.SUBREGION, continent];
}
const out = `/**
 * Country → [UN sub-region, continent] (Natural Earth admin-0 1:50m, public domain),
 * for the expansion ladder (src/sim/company.ts). Generated by pipeline/gen-geo-regions.ts.
 */
export const GEO_REGIONS: Readonly<Record<string, readonly [string, string]>> = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(join(HERE, '..', 'src', 'data', 'geoRegions.ts'), out);
console.log(`${Object.keys(rows).length} countries`);
