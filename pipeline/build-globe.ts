/**
 * Land/water mask for the zoomed-out globe (SPEC §3.5 "Views").
 *
 *   npx tsx build-globe.ts        -> ../src/data/globeLand.ts
 *
 * Reads the `water` layer of the OpenFreeMap planet tiles at z2 (OpenStreetMap
 * data via OpenMapTiles: the same basemap the app already uses and credits,
 * ODbL) and samples a 2° grid: a cell is land when its center is not inside
 * any water polygon. Beyond Web Mercator's ±85.05°, the south is Antarctica
 * and the north is the Arctic Ocean. Output is a ~2 KB base64 bitmask.
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { VectorTile } from '@mapbox/vector-tile';
import { PbfReader } from 'pbf';

const Z = 2;
const STEP = 2;
const ROWS = 180 / STEP;
const COLS = 360 / STEP;
const MERC_MAX = 85.05112878;
const TILEJSON = 'https://tiles.openfreemap.org/planet';

type Ring = { x: number; y: number }[];

async function tileUrl(): Promise<string> {
  const tj = (await (await fetch(TILEJSON)).json()) as { tiles: string[] };
  return tj.tiles[0];
}

/** Water polygons of one tile, as rings in that tile's extent coordinates. */
async function waterRings(
  template: string,
  x: number,
  y: number,
): Promise<{ rings: Ring[]; extent: number }> {
  const url = template
    .replace('{z}', String(Z))
    .replace('{x}', String(x))
    .replace('{y}', String(y));
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  const tile = new VectorTile(new PbfReader(new Uint8Array(await res.arrayBuffer())));
  const layer = tile.layers.water;
  const rings: Ring[] = [];
  let extent = 4096;
  if (layer) {
    extent = layer.extent;
    for (let i = 0; i < layer.length; i++) {
      const f = layer.feature(i);
      if (f.type !== 3) continue;
      for (const ring of f.loadGeometry()) rings.push(ring.map((p) => ({ x: p.x, y: p.y })));
    }
  }
  return { rings, extent };
}

/** Even-odd point-in-polygon over all rings (holes and islands come out right). */
function inside(rings: Ring[], px: number, py: number): boolean {
  let c = false;
  for (const r of rings) {
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const a = r[i];
      const b = r[j];
      if (a.y > py !== b.y > py && px < ((b.x - a.x) * (py - a.y)) / (b.y - a.y) + a.x) c = !c;
    }
  }
  return c;
}

async function main() {
  const template = await tileUrl();
  const n = 2 ** Z;
  const tiles = new Map<string, { rings: Ring[]; extent: number }>();
  for (let x = 0; x < n; x++)
    for (let y = 0; y < n; y++) tiles.set(`${x}/${y}`, await waterRings(template, x, y));

  const bits = new Uint8Array(Math.ceil((ROWS * COLS) / 8));
  let land = 0;
  for (let r = 0; r < ROWS; r++) {
    // Row 0 is the north: cell centers at 89°, 87°, … −89°.
    const lat = 90 - STEP / 2 - r * STEP;
    for (let c = 0; c < COLS; c++) {
      const lng = -180 + STEP / 2 + c * STEP;
      let isLand: boolean;
      if (lat > MERC_MAX) isLand = false;
      else if (lat < -MERC_MAX) isLand = true;
      else {
        const fx = ((lng + 180) / 360) * n;
        const s = Math.sin((lat * Math.PI) / 180);
        const fy = (0.5 - Math.log((1 + s) / (1 - s)) / (4 * Math.PI)) * n;
        const tx = Math.min(n - 1, Math.floor(fx));
        const ty = Math.min(n - 1, Math.floor(fy));
        const t = tiles.get(`${tx}/${ty}`)!;
        isLand = !inside(t.rings, (fx - tx) * t.extent, (fy - ty) * t.extent);
      }
      if (isLand) {
        const i = r * COLS + c;
        bits[i >> 3] |= 1 << (i & 7);
        land++;
      }
    }
  }

  const out = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    '../src/data/globeLand.ts',
  );
  const b64 = Buffer.from(bits).toString('base64');
  await writeFile(
    out,
    `// GENERATED by pipeline/build-globe.ts. Do not edit by hand.
// Land mask for the zoomed-out globe: ${STEP}° cells, row 0 = north, bit i = row * cols + col.
// Source: OpenStreetMap via OpenFreeMap / OpenMapTiles (water layer, z${Z}), ODbL.

export const GLOBE_LAND = {
  stepDeg: ${STEP},
  rows: ${ROWS},
  cols: ${COLS},
  bits: '${b64}',
} as const;
`,
  );
  console.log(
    `globeLand.ts: ${ROWS}×${COLS}, ${((land / (ROWS * COLS)) * 100).toFixed(1)}% land, ${b64.length} chars`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
